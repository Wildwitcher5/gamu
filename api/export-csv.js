function escapeCell(val) {
  if (val === null || val === undefined) return "";
  const str = String(val);
  // Если поле похоже на base64 — заменить заглушкой
  if (str.length > 500 && /^[A-Za-z0-9+/=]+$/.test(str.replace(/^data:[^;]+;base64,/, ""))) {
    return "[картинка]";
  }
  return `"${str.replace(/"/g, '""')}"`;
}

export default async function handler(req, res) {
  if (req.query.secret !== process.env.ADMIN_SECRET) {
    return res.status(401).json({ error: "Unauthorized" });
  }

  const rows = await prisma.response.findMany({
    where: { status: "complete" },
    orderBy: { created_at: "asc" },
    select: { data: true },
  });

  if (rows.length === 0) return res.status(200).send("No data");

  const allData = rows.map(r => r.data);

  const keys   = COLUMN_MAP.map(([k]) => k);
  const labels = COLUMN_MAP.map(([, label]) => label);

  const bom = "\uFEFF";
  const csvRows = [
    labels.map(l => `"${l}"`).join(","),
    ...allData.map(row =>
      keys.map(k => escapeCell(row[k])).join(",")
    ),
  ];

  res.setHeader("Content-Type", "text/csv; charset=utf-8");
  res.setHeader("Content-Disposition", 'attachment; filename="responses_clean.csv"');
  return res.status(200).send(bom + csvRows.join("\r\n"));
}
